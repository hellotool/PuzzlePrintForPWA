import fs from 'node:fs/promises';
import path from 'node:path';
import checker, { type ModuleInfos } from 'license-checker';
import renderEn from '../../templates/NOTICES.md.ts';
import renderZh from '../../templates/NOTICES.zh-CN.md.ts';
import type { Notice } from './notice.ts';
import noticesConfig from './notices.json';

const TARGETS = [
  { output: 'NOTICES.md', template: 'templates/NOTICES.md.ts', render: renderEn },
  { output: 'NOTICES.zh-CN.md', template: 'templates/NOTICES.zh-CN.md.ts', render: renderZh },
];

const HEADER = (template: string) =>
  `<!-- DO NOT EDIT THIS FILE DIRECTLY.
     This file is auto-generated from ${template}.
     Source: scripts/notices/generate.ts, scripts/notices/notices.json
     Generated: ${new Date().toISOString()}
-->

`;

function collectDependencies() {
  return new Promise<ModuleInfos>((resolve, reject) => {
    checker.init(
      {
        start: '.',
        production: true,
        excludePrivatePackages: true,
      },
      (err, packages) => {
        if (err) {
          reject(err);
        } else {
          resolve(packages);
        }
      },
    );
  });
}

async function getCopyrightsFromFile(filePath: string): Promise<string[]> {
  const content = await fs.readFile(filePath, 'utf8');
  return Array.from(content.matchAll(/^\s*(Copyright.*)$/gm), (match) => match[1].trim());
}

async function generateNotices(): Promise<Notice[]> {
  const notices: Notice[] = [];
  for (const [name, packageInfo] of Object.entries(await collectDependencies())) {
    const license = Array.isArray(packageInfo.licenses) ? packageInfo.licenses.join(' ') : packageInfo.licenses;
    let copyrights: string[];
    if (packageInfo.copyright) {
      copyrights = [packageInfo.copyright];
    } else if (packageInfo.licenseFile) {
      copyrights = await getCopyrightsFromFile(packageInfo.licenseFile);
    } else {
      copyrights = [];
    }
    notices.push({ name, license, url: packageInfo.repository, copyrights });
  }
  notices.push(...noticesConfig.notices);
  return notices;
}

const notices = await generateNotices();
for (const { output, template, render } of TARGETS) {
  console.log(`Rendering ${template} -> ${output}`);
  await fs.writeFile(path.resolve(output), `${HEADER(template)}${render(notices).trimEnd()}\n`, 'utf8');
}
